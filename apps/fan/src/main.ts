import { createApp } from 'vue';
import { createPinia } from 'pinia';
import { createNobiI18n, normalizeLocale } from '@nobi/i18n';
import '@nobi/design-tokens/tokens.css';
import '@nobi/design-tokens/base.css';
import App from './App.vue';
import { router } from './router';
import { usePreferences } from './stores/preferences';
import './style.css';
const pinia = createPinia();
const preferences = usePreferences(pinia);
preferences.initialize();
createApp(App).use(pinia).use(createNobiI18n(normalizeLocale(preferences.locale))).use(router).mount('#app');
